/* ============================================================
   Component.js — БАЗОВЫЙ (РОДИТЕЛЬСКИЙ) КЛАСС для всех блоков страницы
   ============================================================
   НАСЛЕДОВАНИЕ:
     Header, HeroSection, ProductsSection, Footer … — все они
     «наследуют» этот класс:   class HeroSection extends Component
     и получают всё, что здесь написано, «бесплатно».

   Что даёт родитель каждому блоку:
     • this.root            — HTML-элемент, в который блок рисует себя;
     • this.languageManager — доступ к переводам;
     • update()             — перерисовать блок;
     • mount()              — первый запуск блока + подписка на смену языка;
     • t() и pick()         — короткие методы для перевода.

   Что ОБЯЗАН написать каждый наследник:
     • render() — вернуть HTML-код блока в виде строки.

   Это как абстрактный класс в Java:
     abstract class Component { abstract String render(); }
   В JavaScript нет слова abstract, поэтому render() здесь
   просто выбрасывает ошибку, если наследник забыл его написать.

   ЖИЗНЕННЫЙ ЦИКЛ блока:
     mount() ─► update() ─► render()      (нарисовать HTML)
                        └─► bindEvents()  (повесить обработчики кликов)
             ─► onMount()                 (одноразовая настройка)
             ─► подписка на смену языка → при смене снова update()
   ============================================================ */

export class Component {

  /* root            — CSS-селектор ('#hero') ИЛИ готовый HTML-элемент
     languageManager — объект LanguageManager (один на весь сайт) */
  constructor(root, languageManager) {
    this.setRoot(root);
    this.languageManager = languageManager;
  }

  /* Установить элемент, в который рисуется блок.
     typeof проверяет тип значения: если передали строку-селектор — ищем элемент на странице. */
  setRoot(root) {
    this.root = typeof root === 'string' ? document.querySelector(root) : root;
  }


  /* ---------- МЕТОДЫ, КОТОРЫЕ ПЕРЕОПРЕДЕЛЯЮТ НАСЛЕДНИКИ ---------- */

  /* «Абстрактный» метод: каждый блок обязан вернуть свой HTML.
     this.constructor.name — имя класса-наследника (например, 'HeroSection'),
     чтобы в ошибке было видно, какой именно класс забыл render(). */
  render() {
    throw new Error(`${this.constructor.name}: нужно написать метод render()`);
  }

  /* Вызывается ПОСЛЕ каждой перерисовки: здесь блок вешает обработчики кликов
     на только что созданные кнопки. По умолчанию ничего не делает. */
  bindEvents() {}

  /* Вызывается ОДИН РАЗ при запуске: здесь вешаются обработчики,
     которые не должны дублироваться (прокрутка окна и т.п.). По умолчанию пусто. */
  onMount() {}


  /* ---------- ОБЩИЕ МЕТОДЫ (наследники используют как есть) ---------- */

  /* Перерисовать блок: вставить HTML из render() внутрь this.root.
     innerHTML — «внутреннее содержимое» элемента. Мы вставляем туда
     ТОЛЬКО свои тексты из папки data, поэтому это безопасно.
     (Никогда не вставляйте так текст, введённый посетителем сайта!) */
  update() {
    if (!this.root) {
      console.warn(`${this.constructor.name}: элемент для блока не найден на странице`);
      return;
    }
    this.root.innerHTML = this.render();
    this.bindEvents();
  }

  /* Запустить блок: нарисовать, выполнить одноразовую настройку
     и подписаться на смену языка.
     () => this.update() — «стрелочная функция»: короткая запись функции.
     Её плюс: внутри неё this по-прежнему указывает на НАШ блок. */
  mount() {
    this.update();
    this.onMount();
    this.languageManager.subscribe(() => this.update());
  }

  /* Короткий способ перевести текст по ключу: this.t('nav.products') */
  t(key) {
    return this.languageManager.translate(key);
  }

  /* Короткий способ выбрать текст из объекта { ru, kz, en }: this.pick(product.name) */
  pick(text) {
    return this.languageManager.pick(text);
  }
}
